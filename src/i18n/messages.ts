export const formatMessage = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))

export const renderHomeMessages = (html: string, locale: Locale): string => html.replace(
  /\{\{(home|status)\.(\w+)\}\}/g,
  (_, namespace: 'home' | 'status', key: string) => {
    const messages: Record<string, string> = namespace === 'home' ? homeMessages[locale] : statusMessages[locale]
    if (!(key in messages)) throw new Error(`Unknown ${namespace} message: ${key}`)
    return escapeHtml(messages[key])
  }
)
