import type { Locale } from '../site'

type Translations = readonly [string, string, string]

const defineMessages = <K extends string>(entries: Record<K, Translations>): Record<Locale, Record<K, string>> => {
  const result = { en: {}, zh: {}, ja: {} } as Record<Locale, Record<K, string>>
  for (const key of Object.keys(entries) as K[]) {
    const [en, zh, ja] = entries[key]
    result.en[key] = en
    result.zh[key] = zh
    result.ja[key] = ja
  }
  return result
}

export const escapeHtml = (value: string): string => value
  .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;').replaceAll("'", '&#39;')

export const scriptJson = (value: unknown): string => JSON.stringify(value)
  .replaceAll('<', '\\u003c').replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029')

